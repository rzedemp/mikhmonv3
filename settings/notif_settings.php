<script>
$(document).ready(function() {
    // Sync URL in details
    $('#gw_url_val').text($('input[name="wa_gateway_url"]').val());
    
    // Status polling
    function pollGatewayStatus() {
        var url = $('input[name="wa_gateway_url"]').val();
        $('#gw_url_val').text(url);
        
        $.ajax({
            url: './admin.php?id=notif&ajax=wa_status',
            dataType: 'json',
            timeout: 3000,
            success: function(data) {
                if (data.online) {
                    $('#gw_service_badge').removeClass('bg-danger bg-warning').addClass('bg-success').text('ONLINE');
                    
                    if (data.connected) {
                        $('#gw_conn_badge').removeClass('bg-danger bg-warning').addClass('bg-success').text('CONNECTED (' + data.user + ')');
                        $('#qr_container').hide();
                    } else if (data.status === 'qrcode' && data.qr) {
                        $('#gw_conn_badge').removeClass('bg-danger bg-success').addClass('bg-warning').text('AWAITING SCAN');
                        // Render QR Code using api.qrserver.com
                        var qrImgUrl = 'https://api.qrserver.com/v1/create-qr-code/?size=200x200&margin=0&data=' + encodeURIComponent(data.qr);
                        $('#qr_image_wrapper').html('<img src="' + qrImgUrl + '" alt="WhatsApp QR Code" style="display:block;margin:0 auto;" />');
                        $('#qr_container').show();
                    } else {
                        $('#gw_conn_badge').removeClass('bg-success bg-warning').addClass('bg-danger').text('DISCONNECTED');
                        $('#qr_container').hide();
                    }
                    
                    // Update Anti-Ban Dashboard
                    if (data.antiBan) {
                        $('#ab_queue').text(data.antiBan.queueLength);
                        $('#ab_daily_count').text(data.antiBan.dailyCount);
                        $('#ab_daily_limit').text(data.antiBan.dailyLimit);
                        $('#ab_hourly_count').text(data.antiBan.hourlyCount);
                        $('#ab_hourly_limit').text(data.antiBan.hourlyLimit);
                        
                        if (data.antiBan.warmupMode) {
                            $('#ab_warmup').removeClass('bg-secondary').addClass('bg-warning').text('ACTIVE (Day ' + data.antiBan.warmupDays + ')');
                        } else {
                            $('#ab_warmup').removeClass('bg-warning').addClass('bg-secondary').text('Disabled');
                        }
                        
                        if (data.antiBan.isPaused) {
                            $('#ab_pause_row').show();
                        } else {
                            $('#ab_pause_row').hide();
                        }
                    }
                } else {
                    $('#gw_service_badge').removeClass('bg-success bg-warning').addClass('bg-danger').text('OFFLINE');
                    $('#gw_conn_badge').removeClass('bg-success bg-warning').addClass('bg-danger').text('OFFLINE');
                    $('#qr_container').hide();
                    
                    // Reset Anti-Ban Dashboard
                    $('#ab_queue').text('-');
                    $('#ab_daily_count').text('-');
                    $('#ab_daily_limit').text('-');
                    $('#ab_hourly_count').text('-');
                    $('#ab_hourly_limit').text('-');
                    $('#ab_warmup').removeClass('bg-warning').addClass('bg-secondary').text('OFFLINE');
                    $('#ab_pause_row').hide();
                }
            },
            error: function() {
                $('#gw_service_badge').removeClass('bg-success bg-warning').addClass('bg-danger').text('OFFLINE');
                $('#gw_conn_badge').removeClass('bg-success bg-warning').addClass('bg-danger').text('OFFLINE');
                $('#qr_container').hide();
                
                // Reset Anti-Ban Dashboard
                $('#ab_queue').text('-');
                $('#ab_daily_count').text('-');
                $('#ab_daily_limit').text('-');
                $('#ab_hourly_count').text('-');
                $('#ab_hourly_limit').text('-');
                $('#ab_warmup').removeClass('bg-warning').addClass('bg-secondary').text('OFFLINE');
                $('#ab_pause_row').hide();
            }
        });
    }
    
    // Poll immediately and every 5 seconds
    pollGatewayStatus();
    setInterval(pollGatewayStatus, 5000);
    
    // Test Telegram Bot
    $('#btnTestTg').click(function() {
        $('#testTgStatus').text('Sending...').css('color', '#888');
        $.ajax({
            url: './admin.php?id=notif&ajax=test_tg',
            dataType: 'json',
            success: function(data) {
                if (data.success) {
                    $('#testTgStatus').text('Test sent successfully!').css('color', '#28a745');
                } else {
                    $('#testTgStatus').text('Failed to send test. Check token/chat_id.').css('color', '#dc3545');
                }
            },
            error: function() {
                $('#testTgStatus').text('Connection error.').css('color', '#dc3545');
            }
        });
    });
    
    // Test WhatsApp
    $('#btnTestWa').click(function() {
        var targets = $('input[name="wa_targets"]').val().split(',');
        var phone = targets[0] ? targets[0].trim() : '';
        if (phone === '') {
            $('#testWaStatus').text('Set a target number first!').css('color', '#dc3545');
            return;
        }
        
        $('#testWaStatus').text('Sending...').css('color', '#888');
        $.ajax({
            url: './admin.php?id=notif&ajax=test_wa&phone=' + encodeURIComponent(phone),
            dataType: 'json',
            success: function(data) {
                if (data.success) {
                    $('#testWaStatus').text('Test sent to ' + phone + '!').css('color', '#28a745');
                } else {
                    $('#testWaStatus').text('Failed to send test. Gateway offline or unconnected.').css('color', '#dc3545');
                }
            },
            error: function() {
                $('#testWaStatus').text('Connection error.').css('color', '#dc3545');
            }
        });
    });
});

        $telegram_chat_id = trim($_POST['telegram_chat_id']);
        
        $wa_enabled = isset($_POST['wa_enabled']) && $_POST['wa_enabled'] === '1';
        $wa_gateway_url = trim($_POST['wa_gateway_url']);
        $wa_gateway_key = trim($_POST['wa_gateway_key']);
        $wa_targets = trim($_POST['wa_targets']);
        
        $cpu_threshold = (float)($_POST['cpu_threshold'] ?? 80.0);
        $memory_threshold = (float)($_POST['memory_threshold'] ?? 85.0);
        
        // Router thresholds override
        $router_thresholds = [];
        if (isset($_POST['router_cpu']) && is_array($_POST['router_cpu'])) {
            foreach ($_POST['router_cpu'] as $r_ses => $r_cpu) {
                $r_mem = $_POST['router_mem'][$r_ses] ?? 85.0;
                $router_thresholds[$r_ses] = [
                    'cpu' => (float)$r_cpu,
                    'mem' => (float)$r_mem
                ];
            }
        }
        
        // Save to include/notif_config.php
        $new_config = [
            'telegram_enabled' => $telegram_enabled,
            'telegram_token'   => $telegram_token,
            'telegram_chat_id' => $telegram_chat_id,
            'wa_enabled'       => $wa_enabled,
            'wa_gateway_url'   => $wa_gateway_url,
            'wa_gateway_key'   => $wa_gateway_key,
            'wa_targets'       => $wa_targets,
            'cpu_threshold'    => $cpu_threshold,
            'memory_threshold' => $memory_threshold,
            'router_thresholds' => $router_thresholds,
        ];
        
        $export = var_export($new_config, true);
        $content = "<?php\n// Mikhmon Notification Configuration\n// Generated by: settings/notif_settings.php\n\n\$notif_config = {$export};\n";
        
        if (file_put_contents('./include/notif_config.php', $content)) {
            $notif_config = $new_config; // Update local reference
            $message_info = '<div class="alert alert-success"><i class="fa fa-check"></i> Configuration saved successfully!</div>';
        } else {
            $message_info = '<div class="alert alert-danger"><i class="fa fa-times"></i> Failed to write config file. Check permissions!</div>';
        }
    }
}

// Handle AJAX actions
if (isset($_GET['ajax'])) {
    header('Content-Type: application/json');
    
    if ($_GET['ajax'] === 'wa_status') {
        $status = check_wa_gateway_status();
        echo json_encode($status);
        exit;
    }
    
    if ($_GET['ajax'] === 'test_tg') {
        $msg = "🔔 *Mikhmon Test Notification*\nTelegram notification integration is working properly!";
        $res = send_telegram_notification($msg);
        echo json_encode(['success' => $res]);
        exit;
    }
    
    if ($_GET['ajax'] === 'test_wa') {
        $phone = $_GET['phone'] ?? '';
        if ($phone === '') {
            $targets = explode(',', $notif_config['wa_targets'] ?? '');
            $phone = trim($targets[0] ?? '');
        }
        if ($phone === '') {
            echo json_encode(['success' => false, 'error' => 'No target phone number set.']);
            exit;
        }
        $msg = "🔔 *Mikhmon Test Notification*\nWhatsApp Baileys gateway integration is working properly!";
        $res = send_wa_notification($phone, $msg);
        echo json_encode(['success' => $res]);
        exit;
    }
}

